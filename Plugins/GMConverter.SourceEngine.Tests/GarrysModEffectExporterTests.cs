using System.Numerics;
using GMConverter.Core.Textures;
using GMConverter.SDK.Exporters;
using GMConverter.SDK.Geometry;
using GMConverter.SDK.Materials;
using GMConverter.SDK.Options;
using GMConverter.SDK.Particles;
using GMConverter.SourceEngine.Exporters;
using GMConverter.SourceEngine.Particles;

namespace GMConverter.SourceEngine.Tests;

public sealed class GarrysModEffectExporterTests
{
    [Fact]
    public void EmittersBecomeLuaInSourceUnitsWithEventSourcesByIndex()
    {
        var lua = GarrysModEffectData.Write(Flare(), _ => Material(), _ => null);

        Assert.StartsWith("-- Generated by GMConverter.\n\nreturn \"P_Flare\", {", lua, StringComparison.Ordinal);
        Assert.Contains("rate = { min = { 0, 60 } },", lua);
        // 10 cm sprites are about four inches; gravity is in inches per second squared.
        Assert.Contains("size = { min = { 0, 3.937008, 3.937008, 3.937008 } },", lua);
        Assert.Contains("acceleration = { 0, 0, -386.220", lua);
        Assert.Contains("events = { { count = { min = { 0, 2 } }, sources = { { 1, \"spawn\" }, { 2, \"death\" } } } },", lua);
        Assert.Contains("params = { [1] = { min = { 0, -1, 1, 3 } } },", lua);
        Assert.Contains("blend = \"additive\"", lua);
        // Five centimetres toward the camera, as CrossFire HD's flares sit in front of the blade.
        Assert.Contains("cameraOffset = { min = { 0, 1.968504 } },", lua);
    }

    [Fact]
    public void MeshDataIsInInchesWithVDownTheImage()
    {
        var model = new Model("arc", [new Mesh(
            [new Vertex(Vector3.Zero, Vector3.UnitZ, new Vector2(0f, 0f)), new Vertex(Vector3.UnitX, Vector3.UnitZ, new Vector2(1f, 0.25f)), new Vertex(Vector3.UnitY, Vector3.UnitZ, new Vector2(0f, 1f))],
            [new Submesh("m", [new Triangle(0, 1, 2)])])], []);

        var data = GarrysModEffectData.MeshData(model);

        Assert.Equal(3, BitConverter.ToInt32(data, 0));
        // The second corner: one metre along X, V flipped back from the SDK's convention.
        Assert.Equal(39.37008f, BitConverter.ToSingle(data, 4 + 20), 3);
        Assert.Equal(0.75f, BitConverter.ToSingle(data, 4 + 20 + 16), 3);
    }

    [Fact]
    public void WithoutAShaderKitTheAddOnIsWrittenWithItsShaderSources()
    {
        var output = Path.Join(Path.GetTempPath(), "GMConverter.GmfxTests", Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(output);
        var options = new OptionValues(new Dictionary<string, object?> { [GarrysModEffectExporter.ShaderKitPathOption] = Path.Join(output, "no-kit") });

        var result = new GarrysModEffectExporter().Export(Flare(), new ExportContext(output, "fx", options));

        Assert.Contains(result.Warnings, warning => warning.Contains("shaders weren't compiled", StringComparison.Ordinal));
        Assert.True(File.Exists(Path.Join(output, "lua", "autorun", "client", "gmconverter_fx.lua")));
        Assert.Contains("GMConverterFX.Register(include(\"gmconverter_fx/effects/fx.lua\"))", File.ReadAllText(Path.Join(output, "lua", "autorun", "gmconverter_fx_fx.lua")));
        Assert.True(File.Exists(Path.Join(output, "materials", "gmconverter", "fx", "fx", "glow.vtf")));
        var sources = Directory.GetFiles(Path.Join(output, "shaders", "src")).Select(Path.GetFileName).ToArray();
        Assert.Contains(sources, file => file!.StartsWith("gmcfx_sprite_", StringComparison.Ordinal) && file.EndsWith("_vs30.hlsl", StringComparison.Ordinal));
        Assert.Contains(sources, file => file!.StartsWith("gmcfx_mesh_", StringComparison.Ordinal));
        // Both emitters draw the same plain material, so they share one pixel shader.
        Assert.Single(sources, file => file!.EndsWith("_ps30.hlsl", StringComparison.Ordinal) && !file.StartsWith("gmcfx_sprite", StringComparison.Ordinal) && !file.StartsWith("gmcfx_mesh", StringComparison.Ordinal));
    }

    private static GarrysModEffectData.EmitterMaterial Material() =>
        new("gmcfx_x_ps30", "gmcfx_sprite_x_vs30", "gmcfx_mesh_x_vs30", [("gmconverter/fx/glow", false)], MaterialBlendMode.Additive);

    private static ParticleEffect Flare()
    {
        var texture = new DefaultTextureFactory().FromRgba("glow", 4, 4, Enumerable.Repeat((byte)200, 64).ToArray(), hasAlpha: true);
        var material = new Material("glow", diffuseTexture: texture, blendMode: MaterialBlendMode.Additive);
        var core = new ParticleEmitter("core", material)
        {
            DurationSeconds = 0.2f,
            SpawnRate = ParticleFloat.Constant(60f),
            Lifetime = ParticleFloat.Constant(0.1f),
            Acceleration = new Vector3(0f, 0f, -9.81f),
            Parameters = [ParticleFloat.Curve([new ParticleKey(0f, -1f), new ParticleKey(1f, 3f)])],
            CameraOffset = ParticleFloat.Constant(0.05f),
        };
        var tail = new ParticleEmitter("tail", material) { DurationSeconds = 0.1f, Bursts = [new ParticleBurst(0f, 1, 1)] };
        var flash = new ParticleEmitter("flash", material)
        {
            EventSpawns = [new ParticleEventSpawn([new ParticleEventSource("core", ParticleEventKind.Spawn), new ParticleEventSource("tail", ParticleEventKind.Death)], ParticleFloat.Constant(2f))],
        };
        return new ParticleEffect("P_Flare", [core, tail, flash]);
    }
}
