using System.Numerics;
using GMConverter.SDK.Materials;
using GMConverter.SDK.Particles;
using GMConverter.SourceEngine.Particles;

namespace GMConverter.SourceEngine.Tests;

public sealed class GarrysModEffectsLuaTests
{
    [Fact]
    public void MeshEmittersRegisterWithTheirSlideAndDimmedColour()
    {
        var emitter = new ParticleEmitter("helix", new Material("helix", blendMode: MaterialBlendMode.Additive, uvTransform: new MaterialUvTransform { Scale = new Vector2(1f, 3f) }))
        {
            Bursts = [new ParticleBurst(0f, 1, 1)],
            Lifetime = ParticleFloat.Constant(2f),
            StartSize = ParticleVector.Constant(new Vector3(-1f, 1f, 1f)),
            ColorOverLife = ParticleVector.Constant(new Vector3(250f, 50f, 4f)),
            UvOffsetOverLife = ParticleVector.Curve([new ParticleVectorKey(0f, new Vector3(0f, 1f, 0f)), new ParticleVectorKey(1f, new Vector3(0f, -3f, 0f))]),
            LocalSpace = true,
        };

        var lua = GarrysModEffectsLua.Effect("P_Arc", [new GarrysModEffectsLua.MeshEmitter(emitter, "models/fx/arc.mdl", "particle/fx/arc", 250f)]);

        Assert.StartsWith("-- Generated by GMConverter.\n\nif not GMConverterEffects then include(\"autorun/client/gmconverter_effects.lua\") end", lua);
        Assert.Contains("GMConverterEffects.RegisterEffect(\"P_Arc\"", lua);
        Assert.Contains("model = \"models/fx/arc.mdl\",", lua);
        Assert.Contains("size = { -1, 1, 1 },", lua);
        Assert.Contains("uvScale = { 1, 3 },", lua);
        Assert.Contains("uvOffset = { { 0, 0, 1 },", lua);
        Assert.Contains("{ 1, 0, -3 } }", lua);
        // The colour comes back within white; the texture carries the brightness.
        Assert.Contains("color = { { 0, 1, 0.2, 0.016 },", lua);
        Assert.Contains("additive = true,", lua);
    }

    [Fact]
    public void TheRuntimeShipsWithThePlugin()
    {
        Assert.Contains("GMConverterEffects", GarrysModEffectsLua.Runtime);
        Assert.Contains("PostDrawViewModel", GarrysModEffectsLua.Runtime);
    }
}
