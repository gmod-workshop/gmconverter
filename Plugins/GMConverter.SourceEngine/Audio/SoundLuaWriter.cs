using System.Globalization;
using System.Text;

namespace GMConverter.SourceEngine.Audio;

/// <summary>
/// Writes sound definitions as Garry's Mod <c>sound.Add</c> calls
/// (https://wiki.facepunch.com/gmod/Structures/SoundData). Garry's Mod does not load sound
/// scripts from add-ons, so Lua that runs on both client and server defines them instead.
/// </summary>
internal static class SoundLuaWriter
{
    public static string Write(IReadOnlyList<SourceSoundDefinition> definitions)
    {
        var text = new StringBuilder();
        text.Append("-- Generated by GMConverter.\n");
        foreach (var definition in definitions)
        {
            text.Append('\n');
            text.Append("sound.Add({\n");
            text.Append("\tname = ").Append(Quote(definition.Name)).Append(",\n");
            text.Append("\tchannel = ").Append(definition.Channel).Append(",\n");
            text.Append("\tvolume = ").Append(Range(Format(definition.VolumeMin), Format(definition.VolumeMax))).Append(",\n");
            text.Append("\tlevel = ").Append(Format(definition.SoundLevel)).Append(",\n");
            text.Append("\tpitch = ").Append(Range(Format(definition.PitchMin), Format(definition.PitchMax))).Append(",\n");
            if (definition.Waves.Count == 1)
            {
                text.Append("\tsound = ").Append(Quote(definition.Waves[0])).Append(",\n");
            }
            else
            {
                text.Append("\tsound = {\n");
                foreach (var wave in definition.Waves)
                {
                    text.Append("\t\t").Append(Quote(wave)).Append(",\n");
                }

                text.Append("\t},\n");
            }

            text.Append("})\n");
        }

        return text.ToString();
    }

    private static string Range(string min, string max) => min == max ? min : $"{{ {min}, {max} }}";

    private static string Format(float value) => value.ToString("0.###", CultureInfo.InvariantCulture);

    private static string Format(int value) => value.ToString(CultureInfo.InvariantCulture);

    private static string Quote(string value) => $"\"{value.Replace("\\", "\\\\").Replace("\"", "\\\"")}\"";
}
