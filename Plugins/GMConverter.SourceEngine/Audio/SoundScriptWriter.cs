using System.Globalization;
using System.Text;

namespace GMConverter.SourceEngine.Audio;

/// <summary>
/// Writes sound definitions as a Source sound script. Games load sound scripts listed in their
/// <c>scripts/game_sounds_manifest.txt</c>.
/// </summary>
internal static class SoundScriptWriter
{
    public static string Write(IReadOnlyList<SourceSoundDefinition> definitions)
    {
        var text = new StringBuilder();
        text.Append("// Generated by GMConverter.\n");
        foreach (var definition in definitions)
        {
            text.Append('\n');
            text.Append(Quote(definition.Name)).Append('\n');
            text.Append("{\n");
            AppendValue(text, "channel", definition.Channel);
            AppendValue(text, "volume", Range(Format(definition.VolumeMin), Format(definition.VolumeMax)));
            AppendValue(text, "pitch", Range(Format(definition.PitchMin), Format(definition.PitchMax)));
            AppendValue(text, "soundlevel", definition.SoundLevel == 0 ? "SNDLVL_NONE" : $"SNDLVL_{Format(definition.SoundLevel)}dB");
            if (definition.Waves.Count == 1)
            {
                AppendValue(text, "wave", definition.Waves[0]);
            }
            else
            {
                text.Append("\t\"rndwave\"\n\t{\n");
                foreach (var wave in definition.Waves)
                {
                    text.Append('\t');
                    AppendValue(text, "wave", wave);
                }

                text.Append("\t}\n");
            }

            text.Append("}\n");
        }

        return text.ToString();
    }

    private static void AppendValue(StringBuilder text, string key, string value)
    {
        text.Append('\t').Append(Quote(key)).Append('\t').Append(Quote(value)).Append('\n');
    }

    private static string Range(string min, string max) => min == max ? min : $"{min}, {max}";

    private static string Format(float value) => value.ToString("0.###", CultureInfo.InvariantCulture);

    private static string Format(int value) => value.ToString(CultureInfo.InvariantCulture);

    // KeyValues has no escapes, so a quote inside a name cannot be written; names come from asset
    // names, which never contain one.
    private static string Quote(string value) => $"\"{value.Replace('"', '\'')}\"";
}
