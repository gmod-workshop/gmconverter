using System.Globalization;
using System.Numerics;
using System.Text;
using GMConverter.SDK.Materials;
using GMConverter.SDK.Particles;

namespace GMConverter.SourceEngine.Particles;

/// <summary>
/// Writes a <see cref="ParticleEffect"/> as the Lua table the Garry's Mod effect runtime
/// (<c>gmconverter_fx.lua</c>) simulates: each emitter's schedule, start values and curves, in Source
/// units (inches, seconds, radians), with its compiled material and, for mesh emitters, its model data.
/// Curves are flat key lists (<c>{ t, v, ... }</c>, vectors <c>{ t, x, y, z, ... }</c>) with min and max.
/// </summary>
internal static class GarrysModEffectData
{
    private const float _inchesPerMetre = 39.3700787f;
    private const int _maximumParticles = 2000;

    /// <summary>How an emitter's material is drawn: its compiled shaders and textures.</summary>
    /// <param name="Shader">The pixel shader's name.</param>
    /// <param name="SpriteShader">The vertex shader for sprites.</param>
    /// <param name="MeshShader">The vertex shader for mesh particles.</param>
    /// <param name="Textures">Each texture's path under <c>materials/</c> and whether it is read linearly (data rather than colour).</param>
    /// <param name="Blend">How it composites.</param>
    public sealed record EmitterMaterial(string Shader, string SpriteShader, string MeshShader, IReadOnlyList<(string Path, bool Linear)> Textures, MaterialBlendMode Blend);

    /// <summary>A Lua chunk returning the effect's name and definition.</summary>
    public static string Write(ParticleEffect effect, Func<ParticleEmitter, EmitterMaterial> materialFor, Func<ParticleEmitter, string?> meshFor)
    {
        var text = new StringBuilder("-- Generated by GMConverter.\n\nreturn ");
        text.Append(Quote(effect.Name)).Append(", {\n\temitters = {\n");
        foreach (var emitter in effect.Emitters)
        {
            Emitter(text, effect, emitter, materialFor(emitter), meshFor(emitter));
        }

        text.Append("\t},\n}\n");
        return text.ToString();
    }

    private static void Emitter(StringBuilder text, ParticleEffect effect, ParticleEmitter emitter, EmitterMaterial material, string? mesh)
    {
        void Field(string name, string value) => text.Append(CultureInfo.InvariantCulture, $"\t\t\t{name} = {value},\n");
        var isMesh = mesh is not null;
        text.Append("\t\t{\n");
        Field("name", Quote(emitter.Name));
        Field("material", Material(material));
        if (mesh is not null)
        {
            Field("mesh", Quote(mesh));
        }

        Field("alignment", emitter.Alignment switch
        {
            ParticleAlignment.Velocity => "1",
            ParticleAlignment.CameraSquare => "2",
            _ => "0",
        });
        Field("localSpace", emitter.LocalSpace ? "true" : "false");
        Field("delay", Number(emitter.DelaySeconds));
        Field("duration", Number(emitter.DurationSeconds));
        Field("loops", emitter.Cycles.ToString(CultureInfo.InvariantCulture));
        Field("max", MaxParticles(emitter).ToString(CultureInfo.InvariantCulture));
        if (emitter.SpawnRate is { } rate)
        {
            Field("rate", Float(rate, 1f));
        }

        Field("bursts", "{ " + string.Join(", ", emitter.Bursts.Select(burst => $"{{ {Number(burst.TimeSeconds)}, {burst.MinCount}, {burst.MaxCount} }}")) + " }");
        var events = emitter.EventSpawns.Select(eventSpawn =>
        {
            var sources = eventSpawn.Sources
                .Select(source => (Index: effect.Emitters.ToList().FindIndex(other => other.Name == source.Emitter), source.Kind))
                .Where(source => source.Index >= 0)
                .Select(source => $"{{ {source.Index + 1}, {(source.Kind == ParticleEventKind.Death ? "\"death\"" : "\"spawn\"")} }}")
                .ToArray();
            return sources.Length == 0 ? null : $"{{ count = {Float(eventSpawn.Count, 1f)}, sources = {{ {string.Join(", ", sources)} }} }}";
        }).OfType<string>().ToArray();
        if (events.Length > 0)
        {
            Field("events", "{ " + string.Join(", ", events) + " }");
        }

        Field("life", Float(emitter.Lifetime, 1f));
        if (emitter.StartLocation is { } location)
        {
            Field("location", Vector(location, _inchesPerMetre));
        }

        if (emitter.StartVelocity is { } velocity)
        {
            Field("velocity", Vector(velocity, _inchesPerMetre));
        }

        if (emitter.RadialVelocity is { } radial)
        {
            Field("radial", Float(radial, _inchesPerMetre));
        }

        if (emitter.VelocityOverLife is { } velocityOverLife)
        {
            Field("velocityOverLife", Vector(velocityOverLife, 1f));
        }

        var acceleration = emitter.Acceleration * _inchesPerMetre;
        Field("acceleration", $"{{ {Number(acceleration.X)}, {Number(acceleration.Y)}, {Number(acceleration.Z)} }}");
        Field("drag", Number(emitter.Drag));
        // Sprites are sized in metres; mesh particles scale their model.
        Field("size", Vector(emitter.StartSize, isMesh ? 1f : _inchesPerMetre));
        if (emitter.SizeOverLife is { } sizeOverLife)
        {
            Field("sizeOverLife", Vector(sizeOverLife, 1f));
        }

        Field("color", Vector(emitter.StartColor, 1f));
        if (emitter.ColorOverLife is { } colorOverLife)
        {
            Field("colorOverLife", Vector(colorOverLife, 1f));
        }

        Field("alpha", Float(emitter.StartAlpha, 1f));
        if (emitter.AlphaOverLife is { } alphaOverLife)
        {
            Field("alphaOverLife", Float(alphaOverLife, 1f));
        }

        if (emitter.StartRotation is { } rotation)
        {
            Field("rotation", Float(rotation, 1f));
        }

        if (emitter.RotationRate is { } rotationRate)
        {
            Field("rotationRate", Float(rotationRate, 1f));
        }

        if (emitter.Sheet is { } sheet)
        {
            var frames = sheet.FrameOverLife is { } frameOverLife ? $", frames = {Float(frameOverLife, 1f)}" : string.Empty;
            Field("sheet", $"{{ columns = {Math.Max(1, sheet.Columns)}, rows = {Math.Max(1, sheet.Rows)}{frames} }}");
        }

        if (emitter.CameraOffset is { } cameraOffset && !isMesh)
        {
            Field("cameraOffset", Float(cameraOffset, _inchesPerMetre));
        }

        if (emitter.Orbit is { } orbit)
        {
            Field("orbit", $"{{ offset = {Vector(orbit.Offset, _inchesPerMetre)}, rotation = {Vector(orbit.Rotation, 1f)}, rate = {Vector(orbit.RotationRate, 1f)} }}");
        }

        var parameters = Enumerable.Range(0, 4).Select(index => index < emitter.Parameters.Count && emitter.Parameters[index] is { } parameter
            ? $"[{index + 1}] = {Float(parameter, 1f)}"
            : null).OfType<string>();
        Field("params", "{ " + string.Join(", ", parameters) + " }");
        text.Append("\t\t},\n");
    }

    private static string Material(EmitterMaterial material)
    {
        var blend = material.Blend switch
        {
            MaterialBlendMode.Additive => "additive",
            MaterialBlendMode.AlphaBlend or MaterialBlendMode.AlphaTest => "translucent",
            _ => "opaque",
        };
        var textures = string.Join(", ", material.Textures.Select(texture => $"{{ {Quote(texture.Path)}, {(texture.Linear ? "true" : "false")} }}"));
        return $"{{ shader = {Quote(material.Shader)}, spriteShader = {Quote(material.SpriteShader)}, meshShader = {Quote(material.MeshShader)}, blend = {Quote(blend)}, textures = {{ {textures} }} }}";
    }

    private static int MaxParticles(ParticleEmitter emitter)
    {
        if (emitter.MaxParticles is > 0 and var max)
        {
            return Math.Min(max, _maximumParticles);
        }

        var lifetime = emitter.Lifetime.Bounds().Max;
        var rate = emitter.SpawnRate?.Bounds().Max ?? 0f;
        var bursts = emitter.Bursts.Sum(burst => burst.MaxCount);
        var events = emitter.EventSpawns.Sum(eventSpawn => (int)MathF.Ceiling(eventSpawn.Count.Bounds().Max) * 64 * eventSpawn.Sources.Count);
        return Math.Clamp((int)MathF.Ceiling((rate * lifetime) + bursts) + events + 8, 8, _maximumParticles);
    }

    private static string Float(ParticleFloat value, float scale)
    {
        string Keys(IReadOnlyList<ParticleKey> keys) => "{ " + string.Join(", ", keys.Select(key => $"{Number(key.Time)}, {Number(key.Value * scale)}")) + " }";
        return value.IsRandom ? $"{{ min = {Keys(value.Min)}, max = {Keys(value.Max)} }}" : $"{{ min = {Keys(value.Min)} }}";
    }

    private static string Vector(ParticleVector value, float scale)
    {
        string Keys(IReadOnlyList<ParticleVectorKey> keys) => "{ " + string.Join(", ", keys.Select(key =>
        {
            var v = key.Value * scale;
            return $"{Number(key.Time)}, {Number(v.X)}, {Number(v.Y)}, {Number(v.Z)}";
        })) + " }";
        return value.IsRandom ? $"{{ min = {Keys(value.Min)}, max = {Keys(value.Max)} }}" : $"{{ min = {Keys(value.Min)} }}";
    }

    private static string Number(float value) => float.IsFinite(value) ? value.ToString("0.######", CultureInfo.InvariantCulture) : "0";

    private static string Quote(string value) =>
        "\"" + value.Replace("\\", "/", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";

    /// <summary>A mesh particle's model as the runtime reads it: vertex count, then x y z (inches) and u v (V down) per triangle corner.</summary>
    public static byte[] MeshData(SDK.Geometry.Model model)
    {
        using var stream = new MemoryStream();
        using var writer = new BinaryWriter(stream);
        var corners = model.Meshes.SelectMany(part => part.Triangles.SelectMany(triangle => new[] { part.Vertices[triangle.A], part.Vertices[triangle.B], part.Vertices[triangle.C] })).ToArray();
        writer.Write(corners.Length);
        foreach (var vertex in corners)
        {
            var position = vertex.Position * _inchesPerMetre;
            writer.Write(position.X);
            writer.Write(position.Y);
            writer.Write(position.Z);
            writer.Write(vertex.TextureCoordinate.X);
            writer.Write(1f - vertex.TextureCoordinate.Y);
        }

        writer.Flush();
        return stream.ToArray();
    }

    /// <summary>A plain material as a graph: its texture (if any), tiled, times the particle's colour and alpha.</summary>
    public static MaterialGraph FallbackGraph(Material material)
    {
        List<MaterialGraphNode> nodes = [new(MaterialGraphOp.ParticleColor, [])];
        List<MaterialGraphTexture> textures = [];
        var texture = material.DiffuseTexture ?? material.EmissiveTexture;
        if (texture is null)
        {
            nodes.Add(new MaterialGraphNode(MaterialGraphOp.Swizzle, [0]) { Components = "xyz" });
            nodes.Add(new MaterialGraphNode(MaterialGraphOp.Swizzle, [0]) { Components = "w" });
            return new MaterialGraph(nodes, textures, 1, 2);
        }

        textures.Add(new MaterialGraphTexture(texture));
        nodes.Add(new MaterialGraphNode(MaterialGraphOp.TexCoord, []));
        var coordinate = 1;
        if (material.UvTransform is { Scale: var scale } && scale != Vector2.One)
        {
            nodes.Add(MaterialGraphNode.Constant(new Vector4(scale, 0f, 0f), 2));
            nodes.Add(new MaterialGraphNode(MaterialGraphOp.Multiply, [1, 2]));
            coordinate = 3;
        }

        nodes.Add(new MaterialGraphNode(MaterialGraphOp.TextureSample, [coordinate]) { Texture = 0 });
        var sample = nodes.Count - 1;
        nodes.Add(new MaterialGraphNode(MaterialGraphOp.Multiply, [sample, 0]));
        var tinted = nodes.Count - 1;
        nodes.Add(new MaterialGraphNode(MaterialGraphOp.Swizzle, [tinted]) { Components = "xyz" });
        nodes.Add(new MaterialGraphNode(MaterialGraphOp.Swizzle, [tinted]) { Components = "w" });
        return new MaterialGraph(nodes, textures, nodes.Count - 2, nodes.Count - 1);
    }
}
