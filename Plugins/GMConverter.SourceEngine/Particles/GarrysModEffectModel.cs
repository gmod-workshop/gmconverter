using System.Globalization;
using System.Text;
using GMConverter.SDK.Animation;

namespace GMConverter.SourceEngine.Particles;

/// <summary>
/// Writes the client Lua that tells the Garry's Mod effect runtime (<c>gmconverter_fx.lua</c>) which
/// effects a model's sequences start: for each sequence, its particle events' times (seconds into
/// the sequence), effect names and attachments, registered with <c>GMConverterFX.RegisterModel</c>.
/// The effects themselves come from gmfx exports, which register under the same names.
/// </summary>
internal static class GarrysModEffectModel
{
    /// <summary>The Lua file, or null when no sequence starts an effect.</summary>
    /// <param name="modelPath">The model's path under <c>models/</c>, as its QC's <c>$modelname</c>.</param>
    /// <param name="sequences">Each sequence the QC writes and the clip it plays.</param>
    public static string? Write(string modelPath, IEnumerable<(AnimationClip Clip, string Sequence)> sequences)
    {
        var started = sequences
            .Where(sequence => sequence.Clip.Layering is null)
            .Select(sequence => (sequence.Sequence, Events: (sequence.Clip.Events ?? [])
                .Where(animationEvent => animationEvent.Kind == AnimationEventKind.ParticleEffect && !string.IsNullOrWhiteSpace(animationEvent.Effect))
                .OrderBy(animationEvent => animationEvent.TimeSeconds)
                .ToList()))
            .Where(sequence => sequence.Events.Count > 0)
            .ToList();
        if (started.Count == 0)
        {
            return null;
        }

        var model = "models/" + modelPath.Replace('\\', '/').ToLowerInvariant();
        var text = new StringBuilder("-- Generated by GMConverter: the effects ").Append(model).Append("'s sequences start.\n\n");
        text.Append("local function register()\n\tGMConverterFX.RegisterModel(").Append(Quote(model)).Append(", {\n");
        foreach (var (sequence, events) in started)
        {
            var entries = events.Select(animationEvent =>
            {
                var attachment = string.IsNullOrWhiteSpace(animationEvent.Bone) ? "nil" : Quote(animationEvent.Bone);
                return string.Create(CultureInfo.InvariantCulture, $"{{ {animationEvent.TimeSeconds:0.######}, {Quote(animationEvent.Effect!)}, {attachment} }}");
            });
            text.Append("\t\t[").Append(Quote(sequence)).Append("] = { ").Append(string.Join(", ", entries)).Append(" },\n");
        }

        text.Append("\t})\nend\n\n");
        // The runtime ships with the effects' add-on and may load after this file.
        text.Append("if GMConverterFX then register() else hook.Add(\"Initialize\", ").Append(Quote("GMConverterFX " + model)).Append(", register) end\n");
        return text.ToString();
    }

    private static string Quote(string value) =>
        "\"" + value.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";
}
