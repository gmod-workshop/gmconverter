using System.Globalization;
using System.Numerics;
using System.Text;
using GMConverter.SDK.Particles;

namespace GMConverter.SourceEngine.Particles;

/// <summary>
/// Garry's Mod Lua for effects Source's particle system can't draw: the shared client runtime
/// (<c>lua/autorun/client/gmconverter_effects.lua</c>), effect definitions for mesh emitters, and the
/// table of which effects a model's sequences start, and when.
/// </summary>
internal static class GarrysModEffectsLua
{
    /// <summary>The runtime's path under an add-on.</summary>
    public static string RuntimePath { get; } = Path.Join("lua", "autorun", "client", "gmconverter_effects.lua");

    private const int _curveSamples = 16;

    // Client autorun files run alphabetically, so a registration can run before the runtime; it loads it (once).
    private const string _header = "-- Generated by GMConverter.\n\nif not GMConverterEffects then include(\"autorun/client/gmconverter_effects.lua\") end\n\n";

    private static readonly Lazy<string> _runtime = new(() =>
    {
        using var stream = typeof(GarrysModEffectsLua).Assembly.GetManifestResourceStream("GMConverter.SourceEngine.Particles.Lua.gmconverter_effects.lua")
            ?? throw new InvalidOperationException("The Garry's Mod effects runtime is missing from the plugin.");
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd();
    });

    public static string Runtime => _runtime.Value;

    /// <summary>One mesh emitter as the runtime draws it.</summary>
    /// <param name="Emitter">The emitter.</param>
    /// <param name="Model">Its compiled mesh, relative to the game directory (<c>models/...mdl</c>).</param>
    /// <param name="Material">Its material, relative to <c>materials/</c>, without extension.</param>
    /// <param name="Brightness">How much its colours were divided by, the texture having been brightened as much.</param>
    public sealed record MeshEmitter(ParticleEmitter Emitter, string Model, string Material, float Brightness);

    /// <summary>Registers <paramref name="effect"/>'s mesh emitters with the runtime.</summary>
    public static string Effect(string effect, IReadOnlyList<MeshEmitter> emitters)
    {
        var text = new StringBuilder(_header);
        text.Append(Invariant($"GMConverterEffects.RegisterEffect({Quote(effect)}, {{\n\temitters = {{\n"));
        foreach (var (emitter, model, material, brightness) in emitters)
        {
            var (lifeMin, lifeMax) = emitter.Lifetime.Bounds();
            var size = emitter.StartSize.Evaluate(0f, new Vector3(0.5f));
            var scale = emitter.Material.UvTransform?.Scale ?? Vector2.One;
            text.Append("\t\t{\n");
            text.Append(Invariant($"\t\t\tmodel = {Quote(model)},\n\t\t\tmaterial = {Quote(material)},\n"));
            text.Append(Invariant($"\t\t\tdelay = {emitter.DelaySeconds}, duration = {emitter.DurationSeconds}, rate = {emitter.SpawnRate?.Evaluate(0f, 0.5f) ?? 0f},\n"));
            text.Append(Invariant($"\t\t\tlife = {{ {lifeMin}, {lifeMax} }},\n"));
            text.Append(Invariant($"\t\t\tbursts = {{ {string.Join(", ", emitter.Bursts.Select(burst => Invariant($"{{ {burst.TimeSeconds}, {(burst.MinCount + burst.MaxCount) / 2} }}")))} }},\n"));
            text.Append(Invariant($"\t\t\tsize = {{ {size.X}, {size.Y}, {size.Z} }},\n"));
            text.Append(Invariant($"\t\t\tuvScale = {{ {scale.X}, {scale.Y} }},\n"));
            if (emitter.UvOffsetOverLife is { } offset)
            {
                text.Append(Invariant($"\t\t\tuvOffset = {Keys(time => { var value = offset.Evaluate(time, new Vector3(0.5f)); return [value.X, value.Y]; })},\n"));
            }

            var color = emitter.ColorOverLife ?? emitter.StartColor;
            text.Append(Invariant($"\t\t\tcolor = {Keys(time => { var value = color.Evaluate(time, new Vector3(0.5f)) / brightness; return [value.X, value.Y, value.Z]; })},\n"));
            var alpha = emitter.AlphaOverLife ?? emitter.StartAlpha;
            text.Append(Invariant($"\t\t\talpha = {Keys(time => [alpha.Evaluate(time, 0.5f)])},\n"));
            text.Append(Invariant($"\t\t\tlocalSpace = {(emitter.LocalSpace ? "true" : "false")},\n"));
            text.Append(Invariant($"\t\t\tadditive = {(emitter.Material.BlendMode == SDK.Materials.MaterialBlendMode.Additive ? "true" : "false")},\n"));
            text.Append("\t\t},\n");
        }

        text.Append("\t},\n})\n");
        return text.ToString();
    }

    /// <summary>Registers which effects <paramref name="model"/>'s sequences start: sequence name to (time, effect, attachment).</summary>
    public static string ModelEvents(string model, IReadOnlyDictionary<string, IReadOnlyList<(float Time, string Effect, string? Attachment)>> sequences)
    {
        var text = new StringBuilder(_header);
        text.Append(Invariant($"GMConverterEffects.RegisterModel({Quote(model)}, {{\n"));
        foreach (var (sequence, events) in sequences.OrderBy(pair => pair.Key, StringComparer.Ordinal))
        {
            text.Append(Invariant($"\t[{Quote(sequence)}] = {{ {string.Join(", ", events.Select(item => Invariant($"{{ {item.Time}, {Quote(item.Effect)}, {Quote(item.Attachment ?? string.Empty)} }}")))} }},\n"));
        }

        text.Append("})\n");
        return text.ToString();
    }

    // A curve sampled evenly over the particle's life as { { t, values... }, ... }.
    private static string Keys(Func<float, float[]> value)
    {
        var keys = Enumerable.Range(0, _curveSamples + 1).Select(step =>
        {
            var time = step / (float)_curveSamples;
            return "{ " + string.Join(", ", value(time).Prepend(time).Select(number => number.ToString("0.#####", CultureInfo.InvariantCulture))) + " }";
        });
        return "{ " + string.Join(", ", keys) + " }";
    }

    private static string Quote(string value) => "\"" + value.Replace("\\", "/", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal) + "\"";

    private static string Invariant(FormattableString value) => value.ToString(CultureInfo.InvariantCulture);
}
