using System.Globalization;
using System.Text;
using GMConverter.SDK.Materials;

namespace GMConverter.SourceEngine.Particles.Shaders;

/// <summary>
/// Writes a <see cref="MaterialGraph"/> as a Shader Model 3 pixel shader for Garry's Mod's
/// <c>screenspace_general_8tex</c>, one statement per node. The shader reads what the particle vertex
/// shaders pass it (<see cref="PixelInput"/>): texture coordinate, particle colour and alpha, age, time
/// and parameters. Output is linear: the engine encodes it, blends additive materials as
/// colour times opacity added to the scene, and translucent ones by opacity.
/// </summary>
internal static class MaterialGraphHlsl
{
    /// <summary>The most textures one shader can sample (<c>screenspace_general_8tex</c>'s samplers).</summary>
    public const int MaximumTextures = 8;

    /// <summary>What the particle vertex shaders hand every generated pixel shader.</summary>
    public const string PixelInput = """
        struct PS_INPUT {
            float2 uv     : TEXCOORD0; // the surface's texture coordinate
            float4 color  : TEXCOORD1; // particle colour (linear, may exceed 1) and alpha
            float4 params : TEXCOORD2; // particle parameters
            float4 misc   : TEXCOORD3; // x = time in seconds, y = particle age 0 to 1
        };
        """;

    /// <summary>The pixel shader for <paramref name="graph"/> drawn with <paramref name="blend"/>.</summary>
    public static string Write(MaterialGraph graph, MaterialBlendMode blend, string comment)
    {
        graph.Validate();
        if (graph.Textures.Count > MaximumTextures)
        {
            throw new NotSupportedException($"the material samples {graph.Textures.Count} textures; Garry's Mod shaders take {MaximumTextures}.");
        }

        var text = new StringBuilder();
        text.AppendLine(CultureInfo.InvariantCulture, $"// Generated by GMConverter from {comment}.");
        text.AppendLine("#include \"common_ps_fxc.h\"");
        text.AppendLine();
        for (var index = 0; index < graph.Textures.Count; index++)
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"sampler Texture{index} : register(s{index});");
        }

        text.AppendLine();
        text.AppendLine(PixelInput);
        text.AppendLine();
        text.AppendLine("float4 main(PS_INPUT In) : COLOR {");
        for (var index = 0; index < graph.Nodes.Count; index++)
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"    {Type(graph.SizeOf(index))} n{index} = {Expression(graph, index)};");
        }

        var emissive = graph.Emissive is { } e ? Cast(graph, e, 3) : "float3(0, 0, 0)";
        var opacity = graph.Opacity is { } o ? $"saturate({Cast(graph, o, 1)})" : "1";
        text.AppendLine(CultureInfo.InvariantCulture, $"    float3 emissive = {emissive};");
        text.AppendLine(CultureInfo.InvariantCulture, $"    float opacity = {opacity};");
        text.AppendLine(blend == MaterialBlendMode.Additive
            ? "    return FinalOutput(float4(emissive * opacity, 1), 0, PIXEL_FOG_TYPE_NONE, TONEMAP_SCALE_LINEAR);"
            : "    return FinalOutput(float4(emissive, opacity), 0, PIXEL_FOG_TYPE_NONE, TONEMAP_SCALE_LINEAR);");
        text.AppendLine("}");
        return text.ToString();
    }

    private static string Expression(MaterialGraph graph, int index)
    {
        var node = graph.Nodes[index];
        var size = graph.SizeOf(index);
        string In(int position, int? width = null) => Cast(graph, node.Inputs[position], width ?? size);
        string Ref(int position) => $"n{node.Inputs[position]}";
        return node.Op switch
        {
            MaterialGraphOp.Constant => Vector(node.Value, size),
            MaterialGraphOp.TexCoord => "In.uv",
            MaterialGraphOp.Time => "In.misc.x",
            MaterialGraphOp.ParticleAge => "In.misc.y",
            MaterialGraphOp.ParticleColor => "In.color",
            MaterialGraphOp.ParticleParameters => "In.params",
            MaterialGraphOp.TextureSample => $"tex2D(Texture{node.Texture}, {In(0, 2)})",
            MaterialGraphOp.Swizzle => graph.SizeOf(node.Inputs[0]) == 1
                ? $"(({Type(size)}){Ref(0)})"
                : $"{Ref(0)}.{node.Components}",
            MaterialGraphOp.Append => $"{Type(size)}({Ref(0)}, {Ref(1)})",
            MaterialGraphOp.Add => $"{In(0)} + {In(1)}",
            MaterialGraphOp.Subtract => $"{In(0)} - {In(1)}",
            MaterialGraphOp.Multiply => $"{In(0)} * {In(1)}",
            MaterialGraphOp.Divide => $"{In(0)} / {In(1)}",
            MaterialGraphOp.Power => $"pow(max({In(0)}, 0), {In(1)})",
            MaterialGraphOp.Min => $"min({In(0)}, {In(1)})",
            MaterialGraphOp.Max => $"max({In(0)}, {In(1)})",
            MaterialGraphOp.Dot => DotProduct(graph, node),
            MaterialGraphOp.OneMinus => $"1 - {In(0)}",
            MaterialGraphOp.Floor => $"floor({In(0)})",
            MaterialGraphOp.Ceil => $"ceil({In(0)})",
            MaterialGraphOp.Frac => $"frac({In(0)})",
            MaterialGraphOp.Abs => $"abs({In(0)})",
            MaterialGraphOp.Sqrt => $"sqrt(max({In(0)}, 0))",
            MaterialGraphOp.Sine => $"sin({In(0)})",
            MaterialGraphOp.Cosine => $"cos({In(0)})",
            MaterialGraphOp.Clamp => $"clamp({In(0)}, {In(1)}, {In(2)})",
            MaterialGraphOp.Lerp => $"lerp({In(0)}, {In(1)}, {In(2)})",
            MaterialGraphOp.Select => $"({In(0, 1)} > {In(1, 1)}) ? {In(2)} : {In(3)}",
            _ => throw new NotSupportedException($"material graph operation {node.Op}"),
        };
    }

    private static string DotProduct(MaterialGraph graph, MaterialGraphNode node)
    {
        var width = MaterialGraph.Broadcast(graph.SizeOf(node.Inputs[0]), graph.SizeOf(node.Inputs[1]));
        return $"dot({Cast(graph, node.Inputs[0], width)}, {Cast(graph, node.Inputs[1], width)})";
    }

    // A node's value as `size` components: a scalar spreads, extra components drop, missing ones are 0.
    private static string Cast(MaterialGraph graph, int index, int size)
    {
        var have = graph.SizeOf(index);
        var name = $"n{index}";
        if (have == size)
        {
            return name;
        }

        if (have == 1)
        {
            return $"(({Type(size)}){name})";
        }

        return have > size
            ? $"{name}.{"xyzw"[..size]}"
            : $"{Type(size)}({name}, {string.Join(", ", Enumerable.Repeat("0", size - have))})";
    }

    private static string Vector(System.Numerics.Vector4 value, int size)
    {
        float[] components = [value.X, value.Y, value.Z, value.W];
        var numbers = string.Join(", ", components.Take(size).Select(Number));
        return size == 1 ? numbers : $"{Type(size)}({numbers})";
    }

    private static string Number(float value) => float.IsFinite(value)
        ? value.ToString("0.0#######", CultureInfo.InvariantCulture)
        : value > 0 ? "1e30" : "-1e30";

    private static string Type(int size) => size == 1 ? "float" : $"float{size}";
}
