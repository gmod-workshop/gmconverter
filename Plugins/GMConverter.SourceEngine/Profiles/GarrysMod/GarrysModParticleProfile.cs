using System.Text;
using GMConverter.SDK.Explorer;
using GMConverter.SDK.Options;
using GMConverter.SDK.Profiles;

namespace GMConverter.SourceEngine.Profiles.GarrysMod;

/// <summary>
/// Garry's Mod, the particle exporter's default target. Add-ons' particle files load through
/// <c>game.AddParticles</c>, so a Lua file under <c>lua/autorun</c> adds the <c>.pcf</c> on both
/// client and server and precaches its systems on the server, which networks them to clients.
/// </summary>
internal sealed class GarrysModParticleProfile : ISourceParticleProfile
{
    private static readonly GarrysModProfile _game = new();

    public string Id => _game.Id;

    public string DisplayName => _game.DisplayName;

    public string Engine => _game.Engine;

    public string ExporterFormat => "pcf";

    public OptionSchema OptionSchema => OptionSchema.Empty;

    public GameMatch Detect(ExplorerTarget target) => _game.Detect(target);

    public (string? RelativePath, string Contents) WriteLoader(string pcfPath, IReadOnlyList<string> systems, string name)
    {
        var text = new StringBuilder("-- Generated by GMConverter.\n\n");
        text.Append(System.Globalization.CultureInfo.InvariantCulture, $"game.AddParticles(\"{pcfPath.Replace(Path.DirectorySeparatorChar, '/')}\")\n");
        if (systems.Count > 0)
        {
            text.Append("\nif SERVER then\n");
            foreach (var system in systems)
            {
                text.Append(System.Globalization.CultureInfo.InvariantCulture, $"\tPrecacheParticleSystem(\"{system}\")\n");
            }

            text.Append("end\n");
        }

        return (Path.Join("lua", "autorun", $"{name}_particles.lua"), text.ToString());
    }
}
