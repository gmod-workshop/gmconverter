using System.Globalization;
using System.Text;
using GMConverter.SDK.Materials;
using GMConverter.SourceEngine.Particles.Shaders;

namespace GMConverter.SourceEngine.Shading;

/// <summary>
/// Writes a lit <see cref="MaterialGraph"/> (one with a <see cref="MaterialGraphSurface"/>) as a Shader
/// Model 3 pixel shader for a model drawn with <c>screenspace_general_8tex</c> and the shared vertex
/// shader (<c>gmc_lit_vs30.hlsl</c>). The surface is shaded by its <see cref="MaterialShading"/> model
/// (<c>gmc_unreal_ggx.hlsl</c>) with the lighting Source gives the model, which the Lua runtime commits
/// before each draw. Models have no tangents in this shader, so the tangent frame comes from screen
/// derivatives of the position and texture coordinate, kept at right angles to the vertex normal.
/// On fullbright maps, which Source draws without lighting, the surface is drawn unlit at its base
/// colour, as Source draws its own models there.
/// </summary>
internal static class LitMaterialHlsl
{
    /// <summary>The most textures a lit material can sample: two of the eight samplers hold the scene's probe and the environment BRDF.</summary>
    public const int MaximumTextures = MaterialGraphHlsl.MaximumTextures - 2;

    /// <summary>The sampler holding the scene's reflection probe (a cubemap).</summary>
    public const int ProbeSampler = 6;

    /// <summary>The sampler holding the environment BRDF table (<see cref="EnvironmentBrdf"/>).</summary>
    public const int BrdfSampler = 7;

    private const string _lightingResource = "GMConverter.SourceEngine.Shading.gmc_unreal_ggx.hlsl";

    private static readonly Lazy<string> _lighting = new(() =>
    {
        using var stream = typeof(LitMaterialHlsl).Assembly.GetManifestResourceStream(_lightingResource)
            ?? throw new InvalidOperationException($"{_lightingResource} is missing from the plugin.");
        using var reader = new StreamReader(stream);
        return reader.ReadToEnd();
    });

    /// <summary>The pixel shader for <paramref name="graph"/>; throws <see cref="NotSupportedException"/> with the reason when it can't be drawn.</summary>
    public static string Write(MaterialGraph graph, string comment)
    {
        graph.Validate();
        if (graph.Surface is not { } surface)
        {
            throw new NotSupportedException("the material is unlit");
        }

        if (surface.Shading != MaterialShading.UnrealGgx)
        {
            throw new NotSupportedException($"its {surface.Shading} shading isn't supported");
        }

        if (graph.Textures.Count > MaximumTextures)
        {
            throw new NotSupportedException($"the material samples {graph.Textures.Count} textures; lit Garry's Mod shaders take {MaximumTextures}.");
        }

        // The normal and roughness come first: the reflection vector and the scene's reflection need them.
        var early = Closure(graph, [surface.Normal, surface.Roughness]);
        foreach (var index in early)
        {
            if (graph.Nodes[index].Op is MaterialGraphOp.ReflectionVector or MaterialGraphOp.SceneReflection)
            {
                throw new NotSupportedException("the material's normal or roughness depends on its own reflection");
            }
        }

        var text = new StringBuilder();
        text.AppendLine(CultureInfo.InvariantCulture, $"// Generated by GMConverter from {comment}.");
        text.AppendLine("#include \"common_ps_fxc.h\"");
        text.AppendLine();
        for (var index = 0; index < graph.Textures.Count; index++)
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"sampler Texture{index} : register(s{index});");
        }

        text.AppendLine(CultureInfo.InvariantCulture, $"samplerCUBE SceneProbe : register(s{ProbeSampler});");
        text.AppendLine(CultureInfo.InvariantCulture, $"sampler EnvironmentBrdf : register(s{BrdfSampler});");
        text.AppendLine("""

            // Set by the Lua runtime: x seconds, y the limit on the GGX distribution, z the reflections'
            // scale, w the probe's last mip; x of the next, 1 when the map is drawn fullbright (unlit).
            // Committed by its lighting draw: the ambient cube and lights.
            const float4 g_Shading : register(c0);
            const float4 g_Unlit : register(c1);
            const float3 g_AmbientCube[6] : register(c4);
            const float4 g_Lights[6] : register(c20);
            """);
        text.AppendLine(_lighting.Value);
        text.AppendLine("""
            struct PS_INPUT {
                float2 uv     : TEXCOORD0;
                float3 world  : TEXCOORD1;
                float3 normal : TEXCOORD2;
                float3 eye    : TEXCOORD3;
                float4 atten  : TEXCOORD4;
            };

            #define TangentToWorld(v) (tangent * (v).x + bitangent * (v).y + geometric * (v).z)

            float4 main(PS_INPUT In) : COLOR {
                float3 geometric = normalize(In.normal);
                float3 view = normalize(In.eye - In.world);
                float3 dp1 = ddx(In.world);
                float3 dp2 = ddy(In.world);
                float2 duv1 = ddx(In.uv);
                float2 duv2 = ddy(In.uv);
                float3 dp2perp = cross(dp2, geometric);
                float3 dp1perp = cross(geometric, dp1);
                float3 tangent = dp2perp * duv1.x + dp1perp * duv2.x;
                float3 bitangent = dp2perp * duv1.y + dp1perp * duv2.y;
                tangent -= geometric * dot(geometric, tangent);
                bitangent -= geometric * dot(geometric, bitangent);
                tangent = dot(tangent, tangent) > 1e-24 ? normalize(tangent) : normalize(cross(geometric, abs(geometric.z) < 0.9 ? float3(0, 0, 1) : float3(1, 0, 0)));
                bitangent = dot(bitangent, bitangent) > 1e-24 ? normalize(bitangent) : cross(geometric, tangent);
                float3 cameraVector = float3(dot(view, tangent), dot(view, bitangent), dot(view, geometric));
            """);

        foreach (var index in early)
        {
            text.AppendLine(MaterialGraphHlsl.Statement(graph, index, Input));
        }

        var normalTs = surface.Normal is { } normalNode ? $"normalize({MaterialGraphHlsl.Value(graph, normalNode, 3)})" : "float3(0, 0, 1)";
        text.AppendLine(CultureInfo.InvariantCulture, $"    float3 normalTs = {normalTs};");
        text.AppendLine("    float3 normal = normalize(TangentToWorld(normalTs));");
        text.AppendLine(CultureInfo.InvariantCulture, $"    float roughness = {MaterialGraphHlsl.Value(graph, surface.Roughness, 1)};");
        text.AppendLine("    float3 reflectionVector = 2 * dot(normalTs, cameraVector) * normalTs - cameraVector;");
        text.AppendLine("    float3 sceneReflection = SceneReflection(normal, view, roughness);");

        var earlySet = early.ToHashSet();
        for (var index = 0; index < graph.Nodes.Count; index++)
        {
            if (!earlySet.Contains(index))
            {
                text.AppendLine(MaterialGraphHlsl.Statement(graph, index, Input));
            }
        }

        if (graph.Opacity is { } opacity)
        {
            text.AppendLine(CultureInfo.InvariantCulture, $"    clip({MaterialGraphHlsl.Value(graph, opacity, 1)} - 0.5);");
        }

        var reflection = surface.Reflection is { } reflectionNode ? MaterialGraphHlsl.Value(graph, reflectionNode, 3) : "sceneReflection";
        var emissive = graph.Emissive is { } emissiveNode ? MaterialGraphHlsl.Value(graph, emissiveNode, 3) : "float3(0, 0, 0)";
        text.AppendLine(CultureInfo.InvariantCulture, $$"""
                float3 baseColor = {{MaterialGraphHlsl.Value(graph, surface.BaseColor, 3)}};
                float3 color = ShadeUnrealGgx(normal, view, In.world, In.atten,
                    baseColor, {{MaterialGraphHlsl.Value(graph, surface.Metallic, 1)}}, {{MaterialGraphHlsl.Value(graph, surface.Specular, 1)}}, roughness, {{reflection}});
                // Fullbright maps have no lighting; Source draws models there unlit, at their colour.
                color = g_Unlit.x > 0.5 ? baseColor : color;
                return FinalOutput(float4(color + {{emissive}}, 1), 0, PIXEL_FOG_TYPE_NONE, TONEMAP_SCALE_LINEAR);
            }
            """);
        return text.ToString();
    }

    private static string? Input(MaterialGraphOp op) => op switch
    {
        MaterialGraphOp.TexCoord => "In.uv",
        MaterialGraphOp.Time => "g_Shading.x",
        MaterialGraphOp.CameraVector => "cameraVector",
        MaterialGraphOp.ReflectionVector => "reflectionVector",
        MaterialGraphOp.SceneReflection => "sceneReflection",
        MaterialGraphOp.TangentToWorld => "TangentToWorld",
        _ => null,
    };

    // The nodes the given outputs read, in evaluation order.
    private static List<int> Closure(MaterialGraph graph, IEnumerable<int?> outputs)
    {
        var needed = new bool[graph.Nodes.Count];
        foreach (var output in outputs)
        {
            if (output is { } node)
            {
                needed[node] = true;
            }
        }

        for (var index = graph.Nodes.Count - 1; index >= 0; index--)
        {
            if (needed[index])
            {
                foreach (var input in graph.Nodes[index].Inputs)
                {
                    needed[input] = true;
                }
            }
        }

        return [.. Enumerable.Range(0, graph.Nodes.Count).Where(index => needed[index])];
    }
}
